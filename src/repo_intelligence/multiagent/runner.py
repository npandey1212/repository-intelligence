"""M16 sequential multi-agent runner (spec §7/§16/§20/§21/§22).

The ENTIRE collaboration is deterministic orchestration around two
existing ``Agent`` instances — no new agent framework, no message bus,
no parallelism:

    task ──INVESTIGATION_REQUEST──▶ Investigator (tools, typed report)
                INVESTIGATION_RESULT ▼
    task ──ANALYSIS_REQUEST──────▶ Analyst (NO tools, typed finding)
                ANALYSIS_RESULT ▼
          deterministic Validator (8 rules, no LLM)
                VALIDATION_RESULT ▼
              final task status

Responsibilities:

* **Typed handoffs only** — every hop is a validated ``AgentMessage``
  (``make_message``); a malformed contract raises ``ContractError``
  instead of being coerced.
* **Shared inputs** — one ``TaskPayload`` and one pinned
  repository/commit scope travel unchanged on every message; the
  validator's ``scope_match`` rule proves it.
* **Bounded execution** — ``RunnerConfig.max_messages`` caps handoffs
  (checked BEFORE appending: exhaustion yields ``BUDGET_EXCEEDED``,
  never a fabricated final message), each agent's own
  ``AgentExecutionConfig`` caps tool calls, and an injectable
  ``clock`` + ``stage_deadline_seconds`` maps a slow stage to
  ``TIMEOUT``. The runner never retries (the project has no retry
  infrastructure).
* **Failure mapping** — any agent exception ends the workflow with a
  concrete status (``FAILED`` / ``BUDGET_EXCEEDED`` for
  ``EXECUTION_LIMIT_REACHED`` / ``TIMEOUT``), no analyst run after a
  failed investigation, and no fabricated answer. Schema-invalid
  structured output (``StructuredOutputValidationError``) is a
  failure, not a default.
* **Observability** — sequence-numbered ``collaboration_events``
  (authoritative list on ``MultiAgentTaskState``) are mirrored onto
  each agent's OWN execution trace (the one trace system) between
  stage windows and re-written through the injected sink.
* **Status machine** — every move goes through
  ``multiagent.status.advance``; terminal states are sealed.

Stage windows (events attached to an agent's trace): from that stage's
first send/receive through its final send — validator events live only
on the task state (the validator has no Agent trace by design).
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Callable, Dict, List, Optional

from ..agent import Agent, AgentError
from ..agent.trace_sink import TraceSink
from .contracts import (
    ArchitectureFinding,
    InvestigationReport,
    TaskPayload,
    ToolFailure,
    ValidationResult,
    ValidationRequest,
    make_message,
    report_json,
)
from .status import (
    BUDGET_EXCEEDED,
    COMPLETED,
    FAILED,
    INCOMPLETE,
    PENDING,
    RUNNING,
    TIMEOUT,
    VALIDATION_FAILED,
    advance,
)
from .validation import validate_collaboration

__all__ = [
    "DEFAULT_MAX_MESSAGES",
    "MultiAgentRunner",
    "MultiAgentTaskState",
    "RunnerConfig",
]

DEFAULT_MAX_MESSAGES = 8


def _utcnow() -> str:
    return datetime.utcnow().isoformat(timespec="seconds") + "Z"


@dataclass
class RunnerConfig:
    """Bounds for the whole collaboration (all optional, explicit)."""

    # Handoff cap: how many typed messages the workflow may append
    # (the six-message happy path needs 6).
    max_messages: int = DEFAULT_MAX_MESSAGES
    # Per-stage wall-clock budget (checked after each stage — the
    # runner never preempts a running Agent; there is no threading).
    stage_deadline_seconds: Optional[float] = None

    def __post_init__(self) -> None:
        if self.max_messages < 1:
            raise ValueError("max_messages must be >= 1")
        if self.stage_deadline_seconds is not None:
            if self.stage_deadline_seconds <= 0:
                raise ValueError(
                    "stage_deadline_seconds must be > 0 when set"
                )


@dataclass
class MultiAgentTaskState:
    """The task record — the only authoritative collaboration log.

    ``collaboration_events`` carries monotonic ``sequence`` numbers
    (timestamps are informational, generated by the runner's clock);
    ``status`` only moves through ``status.advance``.
    """

    task_id: str
    task: TaskPayload
    status: str = PENDING
    investigation_id: Optional[str] = None
    report: Optional[InvestigationReport] = None
    finding: Optional[ArchitectureFinding] = None
    validation: Optional[ValidationResult] = None
    messages: List[Any] = field(default_factory=list)
    collaboration_events: List[Dict[str, Any]] = field(default_factory=list)
    tool_failures: List[ToolFailure] = field(default_factory=list)
    investigator_run_id: Optional[str] = None
    analyst_run_id: Optional[str] = None
    error: Optional[str] = None
    started_at: str = ""
    completed_at: str = ""
    _sequence: int = field(default=0, repr=False)

    @property
    def final_status(self) -> bool:
        return self.status not in (PENDING, RUNNING)


class MultiAgentRunner:
    """Runs one task through Investigator → Analyst → Validator.

    The agents are injected (already constructed with their own
    dispatcher, allowlist, execution budget, and structured-output
    contract — this class never builds a client or a tool).
    """

    def __init__(
        self,
        investigator: Agent,
        analyst: Agent,
        trace_sink: Optional[TraceSink] = None,
        config: Optional[RunnerConfig] = None,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._investigator = investigator
        self._analyst = analyst
        self._trace_sink = trace_sink
        self._config = config if config is not None else RunnerConfig()
        self._clock = clock

    # -- event / message plumbing ----------------------------------------

    def _record(
        self,
        state: MultiAgentTaskState,
        bucket: Optional[List[Dict[str, Any]]],
        operation: str,
        actor: str,
        stage: str,
        **extra: Any,
    ) -> None:
        state._sequence += 1
        event: Dict[str, Any] = {
            "operation": operation,
            "sequence": state._sequence,
            "timestamp": _utcnow(),
            "actor": actor,
            "stage": stage,
        }
        event.update(extra)
        state.collaboration_events.append(event)
        if bucket is not None:
            bucket.append(dict(event))

    def _append_message(
        self,
        state: MultiAgentTaskState,
        message: Any,
        stage: str,
        bucket: Optional[List[Dict[str, Any]]],
    ) -> bool:
        """Append one typed handoff if the budget allows; record the
        ``message.send`` (and any ``message.receive`` pending on the
        recipient's stage window). False = budget exhausted."""
        if len(state.messages) >= self._config.max_messages:
            return False
        state.messages.append(message)
        self._record(
            state,
            bucket,
            "message.send",
            message.sender_agent,
            stage,
            message_type=message.message_type,
            message_id=message.message_id,
        )
        return True

    def _receive_pending(
        self,
        state: MultiAgentTaskState,
        recipient: str,
        stage: str,
        bucket: Optional[List[Dict[str, Any]]],
        received: set,
    ) -> None:
        """Record ``message.receive`` for every message addressed to
        this participant that has not been received yet (in message
        order — the recipient stage acknowledges its inbox)."""
        for message in state.messages:
            if message.message_id in received:
                continue
            if message.recipient_agent != recipient:
                continue
            received.add(message.message_id)
            self._record(
                state,
                bucket,
                "message.receive",
                recipient,
                stage,
                message_type=message.message_type,
                message_id=message.message_id,
            )

    def _finish_window(
        self,
        bucket: List[Dict[str, Any]],
        agent: Agent,
    ) -> None:
        """Mirror this stage's events onto the agent's OWN execution
        trace and re-write it through the sink (the ONE trace system —
        the runner never opens a second one)."""
        trace = agent.last_trace
        if trace is None:
            return
        for event in bucket:
            trace.record_collaboration_event(event)
        if self._trace_sink is not None:
            try:
                self._trace_sink.write(trace)
            except Exception:
                # Observability only (same policy as a failed sink
                # write inside the Agent): never a run failure.
                pass

    def _mark(
        self,
        state: MultiAgentTaskState,
        target: str,
        completed: bool = True,
    ) -> MultiAgentTaskState:
        """Move ``state`` through the status machine (single gate) and
        return it — so ``return self._mark(...)`` always hands back the
        full task record, never a bare status string."""
        state.status = advance(state.status, target)
        if completed and target not in (RUNNING, PENDING):
            state.completed_at = _utcnow()
        return state

    @staticmethod
    def _failure_status(exc: BaseException) -> str:
        if isinstance(exc, AgentError) and exc.termination_reason == (
            "EXECUTION_LIMIT_REACHED"
        ):
            return BUDGET_EXCEEDED
        return FAILED

    def _deadline_exceeded(self, started: float) -> bool:
        budget = self._config.stage_deadline_seconds
        if budget is None:
            return False
        return (self._clock() - started) > budget

    @staticmethod
    def _investigator_question(task: TaskPayload) -> str:
        return (
            "Investigate this repository question and produce your "
            "structured InvestigationReport.\n"
            "question: {question}\n"
            "repository_scope: {repository}\n"
            "commit_scope: {commit}\n"
            "Report findings backed only by evidence you inspected; "
            "carry open questions and uncertainties in the typed "
            "fields.".format(
                question=task.question,
                repository=task.repository_scope,
                commit=task.commit_scope,
            )
        )

    @staticmethod
    def _analyst_question(task: TaskPayload, report: InvestigationReport) -> str:
        return (
            "Analyze the Investigator's typed report and produce your "
            "structured ArchitectureFinding.\n"
            "question: {question}\n"
            "repository_scope: {repository}\n"
            "commit_scope: {commit}\n"
            "investigation_id: {investigation_id}\n"
            "Use ONLY this report's evidence (no independent "
            "investigation):\n{report}".format(
                question=task.question,
                repository=task.repository_scope,
                commit=task.commit_scope,
                investigation_id=report.investigation_id,
                report=report_json(report),
            )
        )

    # -- stages -----------------------------------------------------------

    def run(self, task: TaskPayload) -> MultiAgentTaskState:
        """Execute the full sequential workflow; always returns a
        terminal-state record (raises ``ContractError`` only when the
        runner itself would emit a malformed message — a bug, not a
        workflow outcome)."""
        state = MultiAgentTaskState(
            task_id=uuid.uuid4().hex, task=task, started_at=_utcnow()
        )
        self._mark(state, RUNNING, completed=False)
        received: set = set()

        # ---- stage 1: Investigator --------------------------------------
        window: List[Dict[str, Any]] = []
        request = make_message(
            "INVESTIGATION_REQUEST",
            "task",
            "investigator",
            task,
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(state, request, "investigator", window):
            return self._mark(state, BUDGET_EXCEEDED)
        self._receive_pending(
            state, "investigator", "investigator", window, received
        )
        self._record(
            state, window, "agent.start", "investigator", "investigator"
        )
        stage_started = self._clock()
        try:
            result = self._investigator.run_result(
                self._investigator_question(task)
            )
        except Exception as exc:  # explicit status, no fabricated answer
            self._record(
                state,
                window,
                "agent.end",
                "investigator",
                "investigator",
                status=self._failure_status(exc),
                reason=type(exc).__name__,
            )
            self._finish_window(window, self._investigator)
            state.error = "{}: {}".format(type(exc).__name__, exc)
            if self._deadline_exceeded(stage_started):
                return self._mark(state, TIMEOUT)
            return self._mark(state, self._failure_status(exc))
        if self._deadline_exceeded(stage_started):
            self._record(
                state,
                window,
                "agent.end",
                "investigator",
                "investigator",
                status=TIMEOUT,
                reason="STAGE_DEADLINE_EXCEEDED",
            )
            self._finish_window(window, self._investigator)
            state.error = "stage deadline exceeded"
            return self._mark(state, TIMEOUT)
        report = result.structured_output
        if not isinstance(report, InvestigationReport):
            self._record(
                state,
                window,
                "agent.end",
                "investigator",
                "investigator",
                status=FAILED,
                reason="MISSING_STRUCTURED_OUTPUT",
            )
            self._finish_window(window, self._investigator)
            state.error = "investigator produced no typed InvestigationReport"
            return self._mark(state, FAILED)
        state.report = report
        state.investigation_id = report.investigation_id
        if self._investigator.last_trace is not None:
            state.investigator_run_id = self._investigator.last_trace.run_id
        self._record(
            state,
            window,
            "agent.end",
            "investigator",
            "investigator",
            status=COMPLETED,
        )
        result_message = make_message(
            "INVESTIGATION_RESULT",
            "investigator",
            "analyst",
            report,
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(
            state, result_message, "investigator", window
        ):
            self._finish_window(window, self._investigator)
            state.error = "message budget exhausted after investigation"
            return self._mark(state, BUDGET_EXCEEDED)
        self._finish_window(window, self._investigator)

        # ---- stage 2: Analyst -------------------------------------------
        window = []
        analysis_request = make_message(
            "ANALYSIS_REQUEST",
            "task",
            "analyst",
            report,
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(
            state, analysis_request, "analyst", window
        ):
            state.error = "message budget exhausted before analysis"
            return self._mark(state, BUDGET_EXCEEDED)
        self._receive_pending(state, "analyst", "analyst", window, received)
        self._record(state, window, "agent.start", "analyst", "analyst")
        stage_started = self._clock()
        try:
            result = self._analyst.run_result(
                self._analyst_question(task, report)
            )
        except Exception as exc:
            self._record(
                state,
                window,
                "agent.end",
                "analyst",
                "analyst",
                status=self._failure_status(exc),
                reason=type(exc).__name__,
            )
            self._finish_window(window, self._analyst)
            state.error = "{}: {}".format(type(exc).__name__, exc)
            if self._deadline_exceeded(stage_started):
                return self._mark(state, TIMEOUT)
            return self._mark(state, self._failure_status(exc))
        if self._deadline_exceeded(stage_started):
            self._record(
                state,
                window,
                "agent.end",
                "analyst",
                "analyst",
                status=TIMEOUT,
                reason="STAGE_DEADLINE_EXCEEDED",
            )
            self._finish_window(window, self._analyst)
            state.error = "stage deadline exceeded"
            return self._mark(state, TIMEOUT)
        finding = result.structured_output
        if not isinstance(finding, ArchitectureFinding):
            self._record(
                state,
                window,
                "agent.end",
                "analyst",
                "analyst",
                status=FAILED,
                reason="MISSING_STRUCTURED_OUTPUT",
            )
            self._finish_window(window, self._analyst)
            state.error = "analyst produced no typed ArchitectureFinding"
            return self._mark(state, FAILED)
        state.finding = finding
        if self._analyst.last_trace is not None:
            state.analyst_run_id = self._analyst.last_trace.run_id
        self._record(
            state, window, "agent.end", "analyst", "analyst", status=COMPLETED
        )
        analysis_result = make_message(
            "ANALYSIS_RESULT",
            "analyst",
            "task",
            finding,
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(
            state, analysis_result, "analyst", window
        ):
            self._finish_window(window, self._analyst)
            state.error = "message budget exhausted after analysis"
            return self._mark(state, BUDGET_EXCEEDED)
        self._finish_window(window, self._analyst)

        # ---- stage 3: deterministic validator ---------------------------
        window = []
        validation_request = make_message(
            "VALIDATION_REQUEST",
            "task",
            "validator",
            ValidationRequest(
                investigation_id=report.investigation_id,
                repository_scope=task.repository_scope,
                commit_scope=task.commit_scope,
            ),
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(
            state, validation_request, "validator", window
        ):
            state.error = "message budget exhausted before validation"
            return self._mark(state, BUDGET_EXCEEDED)
        self._receive_pending(
            state, "validator", "validator", window, received
        )
        self._record(state, window, "validator.start", "validator", "validator")
        verdict = validate_collaboration(
            task=task,
            report=report,
            finding=finding,
            investigator_trace=self._investigator.last_trace,
            messages=state.messages,
            analyst_trace=self._analyst.last_trace,
        )
        state.validation = verdict
        state.tool_failures = list(verdict.tool_failures)
        # Stage sealed first (mirroring agent.end), then the typed
        # verdict crosses the boundary as the final handoff.
        self._record(
            state,
            window,
            "validator.complete",
            "validator",
            "validator",
            status=verdict.status,
        )
        validation_result_message = make_message(
            "VALIDATION_RESULT",
            "validator",
            "task",
            verdict,
            task.repository_scope,
            task.commit_scope,
        )
        if not self._append_message(
            state, validation_result_message, "validator", window
        ):
            state.error = "message budget exhausted after validation"
            return self._mark(state, BUDGET_EXCEEDED)
        if verdict.status != "passed":
            return self._mark(state, VALIDATION_FAILED)
        if report.status == "incomplete" or finding.status == "incomplete":
            return self._mark(state, INCOMPLETE)
        return self._mark(state, COMPLETED)
